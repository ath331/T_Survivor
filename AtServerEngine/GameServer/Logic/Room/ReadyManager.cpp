#include "pch.h"
#include "ReadyManager.h"


////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 플레이어 레디를 처리한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtVoid ReadyManager::ReadyPlayer( PlayerPtr player )
{
	if ( !player )
		return;

	m_readyPlayerSet.insert( player );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 플레이어 레디 취소를 처리한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtVoid ReadyManager::ReadyCanclePlayer( PlayerPtr player )
{
	if ( !player )
		return;

	auto iter = m_readyPlayerSet.find( player );
	if ( iter == m_readyPlayerSet.end() )
		return;

	m_readyPlayerSet.erase( iter );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 레디중인 인원수를 반환한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtInt8 ReadyManager::GetReadyCount() const
{
	return static_cast< AtInt8 >( m_readyPlayerSet.size() );
}
