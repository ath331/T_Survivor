#pragma once


class Cheat;


////////////////////////////////////////////////////////////////////////////////////////////////////
// @brief Cheat Class
////////////////////////////////////////////////////////////////////////////////////////////////////
class Cheat
{
protected:
	/// 치트 명령어 파람 리스트 타입
	using ParamList = std::vector< AtString >;

public:
	/// 치트를 등록한다.
	AtVoid AddCmd( const AtString& cmd );

	/// 치트를 동작한다.
	AtVoid Run( PlayerPtr player, const AtString& msg );

private:
	/// 파람값을 파싱한다
	ParamList _SplitBySpace( const AtString& msg );

protected:
	/// 치트를 동작한다.
	virtual AtVoid _Run( PlayerPtr player, const ParamList& paramList ) = 0;
};