////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 생성자
////////////////////////////////////////////////////////////////////////////////////////////////////
WaitingRoom::WaitingRoom(
	AtInt32  maxUserCount,
	AtString name,
	AtInt32  pw )
	:
	m_maxUserCount( maxUserCount ),
	m_name( name ),
	m_pw( pw )
{
	m_state = ERoomState::ROOM_STATE_NONE;
	m_isPrivate = ( 0 < m_pw );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 룸을 업데이트한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtVoid WaitingRoom::UpdateTick( Millisecond curTime )
{
	if ( m_state != ROOM_STATE_WAITING && m_state != ROOM_STATE_PLAY )
		return;

	if ( GetPlayerCount() <= 0 )
		m_state = ROOM_STATE_DESTROY_RESERVATION;

	// GLobby에서 Update()로 접근하므로 다시 호출하면 안됨.
	//Room::UpdateTick( curTime );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 정보를 내보낸다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtVoid WaitingRoom::ExportTo( RoomInfo& roomInfo )
{
	Room::ExportTo( roomInfo );

	roomInfo.set_name      ( m_name           );
	roomInfo.set_pw        ( m_pw             );
	roomInfo.set_max_count ( m_maxUserCount   );
	roomInfo.set_room_state( m_state          );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 방에 입장할 수 있는지 확인한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtBool WaitingRoom::CheckEnterRoom() const
{
	if ( m_maxUserCount <= GetPlayerCount() )
		return false;

	switch ( m_state )
	{
	case ROOM_STATE_DESTROY_RESERVATION:
	case ROOM_STATE_MAX:
		return false;
	}

	return true;
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 플레이어 레디를 처리한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtVoid WaitingRoom::ReadyPlayer( PlayerPtr player )
{
	m_readyManager.ReadyPlayer( player );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 플레이어 레디 취소를 처리한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtVoid WaitingRoom::ReadyCanclePlayer( PlayerPtr player )
{
	m_readyManager.ReadyCanclePlayer( player );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 모든 플레이어가 레디 상태인지 확인한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtBool WaitingRoom::IsAllPlayerReady()
{
	AtInt8 playerCount = static_cast< AtInt8 >( GetPlayerCount() );

	return m_readyManager.GetReadyCount() == playerCount;
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 플레이어가 방에 입장한 다음 처리한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtVoid WaitingRoom::_OnPlayerEnter( PlayerPtr player )
{
	m_state = ROOM_STATE_WAITING;
}
