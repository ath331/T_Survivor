////////////////////////////////////////////////////////////////////////////////////////////////////
// @brief 치트를 등록한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtVoid Cheat::AddCmd( const AtString& cmd )
{
	AtString lowerCmd = cmd;
	std::transform( lowerCmd.begin(), lowerCmd.end(), lowerCmd.begin(),
				   []( unsigned char c ) { return std::tolower( c ); } );


	CheatManager::GetInstance().AddCmd( lowerCmd, this );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @brief 치트를 동작한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtVoid Cheat::Run( PlayerPtr player, const AtString& msg )
{
	ParamList paramList = _SplitBySpace( msg );

	_Run( player, paramList );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @brief 파람값을 파싱한다
////////////////////////////////////////////////////////////////////////////////////////////////////
Cheat::ParamList Cheat::_SplitBySpace( const AtString& msg )
{
	ParamList result;
	std::istringstream iss( msg );
	std::string token;

	while ( iss >> token )
		result.push_back( token );

	// cmd 제거
	// 벡터에서 앞쪽 원소 삭제는 비효율이지만 치트니깐 뭐..
	result.erase( result.begin() );

	return result;
}
