////////////////////////////////////////////////////////////////////////////////////////////////////
// @brief 치트를 등록한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtVoid CheatManager::AddCmd( const AtString& cmd, Cheat* cheat )
{
	auto [ iter, result ] = m_cheatMap.insert( { cmd, cheat } );
	if ( !result )
		ERROR_LOG( "Duplicate Log. name : \"" + cmd + "\"" );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @brief 메시지가 치트인지 확인한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtBool CheatManager::IsCheat( const AtString& msg )
{
	if ( msg.empty() )
		return false;

	return msg[ 0 ] == '@';
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @brief 치트를 동작한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtVoid CheatManager::Run( PlayerPtr player, const AtString& msg )
{
	if ( msg.empty() )
		return;

	Cheat* cheat = _GetObject( msg );
	if ( !cheat )
		return;

	cheat->Run( player, msg );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @brief 치트 객체를 반환한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
Cheat* CheatManager::_GetObject( const AtString& msg )
{
	AtString temp = msg;

	if ( !temp.empty() )
		temp.erase( 0, 1 );

	size_t pos = temp.find( ' ' );
	AtString result = ( pos == std::string::npos ) ? temp : temp.substr( 0, pos );

	auto iter = m_cheatMap.find( result );
	if ( iter == m_cheatMap.end() )
		return nullptr;

	return iter->second;
}
