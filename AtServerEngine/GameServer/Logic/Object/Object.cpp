#include "pch.h"
#include "Object.h"
#include <cmath>
#include <algorithm>


////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 생성자
////////////////////////////////////////////////////////////////////////////////////////////////////
Object::Object()
{
	objectInfo = new Protocol::ObjectInfo();
	posInfo    = new Protocol::PosInfo();

	objectInfo->set_allocated_pos_info( posInfo );
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 소멸자
////////////////////////////////////////////////////////////////////////////////////////////////////
Object::~Object()
{
	// set_allocated_pos_info로 posInfo를 들고 있기때문에 objectInfo가 날아갈때 posInfo도 같이 날아감.
	if ( objectInfo )
	{
		delete objectInfo;
		objectInfo = nullptr;
	}
}

////////////////////////////////////////////////////////////////////////////////////////////////////
// @breif 목표 좌표에 있는지 확인한다.
////////////////////////////////////////////////////////////////////////////////////////////////////
AtBool Object::IsSameNode( float destX, float destZ ) const
{
	// 허용 오차 범위
	float epsilon = 1e-5f;

	float dx = posInfo->x() - destX;
	float dz = posInfo->z() - destZ;

	// 두 좌표 사이 거리
	float dist = std::sqrt( dx * dx + dz * dz );

	// 비교 기준 (절대/상대 오차 모두 고려)
	float maxVal = std::max( { 1.0f, std::fabs( posInfo->x() ), std::fabs( posInfo->z() ),
							 std::fabs( destX ), std::fabs( destZ ) } );

	return dist <= epsilon * maxVal;
}
